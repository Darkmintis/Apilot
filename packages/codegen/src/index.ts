const RESERVED = new Set([
  // shared across Dart / TS / Kotlin / Swift
  "class", "default", "new", "switch", "case", "return", "if", "else", "for", "while", "do", "break", "continue",
  "var", "val", "let", "const", "final", "static", "this", "super", "null", "true", "false", "is", "in", "as",
  "enum", "extends", "import", "export", "package", "interface", "object", "fun", "func", "struct", "protocol",
  "operator", "try", "catch", "throw", "throws", "typealias", "where", "when", "void", "dynamic", "required",
  "extension", "self", "Type", "init", "deinit", "internal", "private", "public", "open", "override", "get", "set",
  // members generated models already have
  "hashCode", "runtimeType", "toString", "copyWith", "toJson", "noSuchMethod",
]);

function words(s: string): string[] {
  return s
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
}

export function camel(s: string): string {
  return words(s).map((w, i) => (i ? w[0]!.toUpperCase() + w.slice(1).toLowerCase() : w.toLowerCase())).join("");
}

export function pascal(s: string): string {
  const c = camel(s);
  return c ? c[0]!.toUpperCase() + c.slice(1) : "";
}

function identifier(key: string): string {
  let id = camel(key) || "field";
  if (/^\d/.test(id)) id = `n${id}`;
  return RESERVED.has(id) ? `${id}Value` : id;
}
