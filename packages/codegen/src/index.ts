/**
 * Codegen — typed models + a thin API call from an endpoint's real responses.
 *
 * One model walker turns the inferred schema into named classes and enums;
 * each language only renders them:
 *  - Dart/Flutter (flagship): freezed + json_serializable (or plain classes), Dio call
 *  - TypeScript: zod schemas + inferred types, fetch call
 *  - Kotlin: kotlinx.serialization data classes, Retrofit interface
 *  - Swift: Codable structs, URLSession call
 *
 * Like quicktype: identical shapes share one class, array items get singular
 * names, ISO dates become date types, repeated string values become enums
 * (with an `unknown` fallback so a new server value never crashes decoding),
 * and objects keyed by ids become maps.
 *
 * Generated files carry a header. Files without it are hand-written and are
 * never overwritten; identical output is not rewritten (diff-aware regen).
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import type { ApilotSchema, Workspace } from "@apilot/core";

export const LANGUAGES = ["dart", "typescript", "kotlin", "swift"] as const;
export type Language = (typeof LANGUAGES)[number];

export const GENERATED_MARKER = "GENERATED BY APILOT";

export interface EndpointSpec {
  id: string;
  name: string;
  method: string;
  url: string;
  schema: ApilotSchema;
}

export interface GeneratedFile {
  /** path relative to the project root */
  path: string;
  content: string;
  language: Language;
}

export interface RenderOptions {
  /** dart: "freezed" (default) | "plain" */
  flavor?: string;
  /** kotlin package name */
  packageName?: string;
}

