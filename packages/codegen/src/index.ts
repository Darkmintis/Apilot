type T =
  | { k: "string" | "int" | "double" | "bool" | "any" | "date" }
  | { k: "map"; of?: T }
  | { k: "model"; name: string }
  | { k: "enum"; name: string }
  | { k: "list"; of: T };

interface Field {
  key: string;
  /** identifier in the target language (camelCase, sanitized) */
  name: string;
  type: T;
  required: boolean;
  nullable: boolean;
}

interface Model {
  name: string;
  fields: Field[];
}

export interface EnumModel {
  name: string;
  values: string[];
}

/** Keys that are ids rather than field names: `{"17": {...}, "42": {...}}`. */
const DYNAMIC_KEY = /^(\d+|[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|[0-9a-f]{16,})$/i;
/** Wrapper keys whose items are better named after the endpoint's resource. */
const GENERIC_LIST_KEY = /^(data|items|results|records|list|rows|content|entries|values|payload|docs|nodes|edges)$/i;

const typeSig = (t: T): string =>
  t.k === "model" || t.k === "enum" ? `${t.k}:${t.name}` : t.k === "list" ? `list<${typeSig(t.of)}>` : t.k === "map" ? `map<${t.of ? typeSig(t.of) : ""}>` : t.k;

/**
 * Collect models in dependency order (children before parents).
 * `itemHint` names the items of a top-level or generic array (e.g. "Order" for orders.list).
 */
export function collectModels(schema: ApilotSchema, rootName: string, itemHint?: string): { root: T; models: Model[]; enums: EnumModel[] } {
  const models: Model[] = [];
  const enums: EnumModel[] = [];
  const used = new Set<string>();
  const bySig = new Map<string, string>();

  /** Prefer `candidate`; on a clash with a different shape use `ParentCandidate`, then numbered. */
  const claim = (candidate: string, parent: string): string => {
    let name = !used.has(candidate) ? candidate : !used.has(parent + candidate) ? parent + candidate : "";
    if (!name) for (let i = 2; !name || used.has(name); i++) name = `${parent}${candidate}${i}`;
    used.add(name);
    return name;
  };

  const walk = (s: ApilotSchema | undefined, name: string, parent: string): T => {
    switch (s?.type) {
      case "string": {
        if (s.format) return { k: "date" };
        const values = (s.enum ?? []).filter((v): v is string => typeof v === "string" && v !== "");
        if (values.length < 2) return { k: "string" };
        const sig = `enum:${values.join("\u0000")}`;
        const existing = bySig.get(sig);
        if (existing) return { k: "enum", name: existing };
        const enumName = claim(name, parent);
        bySig.set(sig, enumName);
        enums.push({ name: enumName, values });
        return { k: "enum", name: enumName };
      }
      case "integer":
        return { k: "int" };
      case "number":
        return { k: "double" };
      case "boolean":
        return { k: "bool" };
      case "array":
        return { k: "list", of: walk(s.items, name, parent) };
      case "object": {
        const props = Object.entries(s.properties ?? {});
        if (props.length === 0) return { k: "map" };
        if (props.length >= 2 && props.every(([k]) => DYNAMIC_KEY.test(k))) {
          const shapes = new Set(props.map(([, v]) => JSON.stringify(v)));
          if (shapes.size === 1) return { k: "map", of: walk(props[0]![1], singular(name) === name ? `${name}Value` : singular(name), parent) };
          return { k: "map" };
        }
        const ids = new Set<string>();
        const fields = props.map(([key, prop]): Field => {
          let id = identifier(key);
          for (let i = 2; ids.has(id); i++) id = `${identifier(key)}${i}`;
          ids.add(id);
          return { key, name: id, type: walk(prop, childName(key, prop, itemHint), name), required: s.required.includes(key), nullable: prop.nullable || !prop.type };
        });
        const sig = `model:${JSON.stringify(fields.map((f) => [f.key, typeSig(f.type), f.required, f.nullable]))}`;
        const existing = bySig.get(sig);
        if (existing) return { k: "model", name: existing };
        const modelName = claim(name, parent);
        bySig.set(sig, modelName);
        models.push({ name: modelName, fields });
        return { k: "model", name: modelName };
      }
      default:
        return { k: "any" };
    }
  };

  const top = schema.type === "array" ? itemHint || `${rootName}Item` : rootName;
  return { root: walk(schema, top, rootName), models, enums };
}

/** Class name for a field's value: singular for arrays (`orders` → `Order`). */
function childName(key: string, prop: ApilotSchema, itemHint?: string): string {
  const base = pascal(key) || "Field";
  if (prop.type !== "array") return base;
  if (GENERIC_LIST_KEY.test(key) && itemHint) return itemHint;
  const one = pascal(singular(key));
  return one && one !== base ? one : `${base}Item`;
}

export function singular(word: string): string {
  if (/[^aeiou]ies$/i.test(word)) return word.slice(0, -3) + "y";
  if (/(ss|us|is|news|data)$/i.test(word)) return word;
  if (/(x|ch|sh|ss)es$/i.test(word)) return word.slice(0, -2);
  if (/s$/i.test(word) && word.length > 3) return word.slice(0, -1);
  return word;
}

