/** Generate files for an endpoint from its learned schema (does not write). */
export function generate(ws: Workspace, endpointId: string, language: string, opts: { outDir?: string; flavor?: string } = {}): GeneratedFile[] {
  const lang = assertLanguage(language);
  const { definition } = ws.endpoint(endpointId);
  const target = ws.project.codegen?.[lang];
  const outDir = opts.outDir ?? target?.output ?? `.apilot/generated/${lang}`;
  const spec = { id: endpointId, name: definition.name, method: definition.method, url: definition.url, schema: ws.schema(endpointId) };
  const content = render(spec, lang, { flavor: opts.flavor ?? target?.flavor, packageName: (target as { package?: string } | undefined)?.package });
  return [{ path: join(outDir, fileName(endpointId, lang)), content, language: lang }];
}

/** Write generated files, skipping hand-written files and unchanged output. */
export function writeGenerated(root: string, files: GeneratedFile[]): { written: string[]; unchanged: string[]; skipped: string[] } {
  const result = { written: [] as string[], unchanged: [] as string[], skipped: [] as string[] };
  for (const f of files) {
    const full = join(root, f.path);
    if (existsSync(full)) {
      const current = readFileSync(full, "utf-8");
      if (current === f.content) {
        result.unchanged.push(f.path);
        continue;
      }
      if (!current.includes(GENERATED_MARKER)) {
        result.skipped.push(f.path);
        continue;
      }
    }
    mkdirSync(dirname(full), { recursive: true });
    writeFileSync(full, f.content);
    result.written.push(f.path);
  }
  return result;
}

export function fileName(endpointId: string, lang: Language): string {
  const base = endpointId.split(/[./-]+/).filter(Boolean);
  switch (lang) {
    case "dart":
      return `${base.map((s) => s.toLowerCase()).join("_")}.dart`;
    case "typescript":
      return `${base.map((s, i) => (i ? pascal(s) : camel(s))).join("")}.ts`;
    case "kotlin":
      return `${pascal(base.join("_"))}.kt`;
    case "swift":
      return `${pascal(base.join("_"))}.swift`;
  }
}

function assertLanguage(language: string): Language {
  if (!(LANGUAGES as readonly string[]).includes(language)) {
    throw new Error(`Unsupported language "${language}". Use one of: ${LANGUAGES.join(", ")}.`);
  }
  return language as Language;
}

